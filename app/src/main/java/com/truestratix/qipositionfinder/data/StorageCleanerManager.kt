package com.truestratix.qipositionfinder.data

import android.content.Context
import android.os.Environment
import android.os.StatFs
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File

data class JunkItem(
    val name: String,
    val sizeBytes: Long,
    val description: String,
    val isAppInternal: Boolean
)

data class CleanerScanResult(
    val appCacheBytes: Long = 0L,
    val externalCacheBytes: Long = 0L,
    val tempFilesBytes: Long = 0L,
    val totalJunkBytes: Long = 0L,
    val totalStorageBytes: Long = 0L,
    val freeStorageBytes: Long = 0L,
    val items: List<JunkItem> = emptyList()
)

class StorageCleanerManager(private val context: Context) {

    suspend fun scanJunk(): CleanerScanResult = withContext(Dispatchers.IO) {
        val items = mutableListOf<JunkItem>()

        // 1. Internal App Cache
        val internalCache = context.cacheDir
        val internalCacheSize = getFolderSize(internalCache)
        if (internalCacheSize > 0) {
            items.add(
                JunkItem(
                    name = "Temporary App Cache",
                    sizeBytes = internalCacheSize,
                    description = "Temporary cache generated by active apps",
                    isAppInternal = true
                )
            )
        }

        // 2. External App Cache
        val externalCache = context.externalCacheDir
        val externalCacheSize = getFolderSize(externalCache)
        if (externalCacheSize > 0) {
            items.add(
                JunkItem(
                    name = "External Cache Buffers",
                    sizeBytes = externalCacheSize,
                    description = "Transient media buffers and decode caches",
                    isAppInternal = true
                )
            )
        }

        // 3. App Code Cache
        val codeCache = context.codeCacheDir
        val codeCacheSize = getFolderSize(codeCache)
        if (codeCacheSize > 0) {
            items.add(
                JunkItem(
                    name = "Code Cache & JIT Logs",
                    sizeBytes = codeCacheSize,
                    description = "Compiled bytecode cache and runtime traces",
                    isAppInternal = true
                )
            )
        }

        // Calculate device storage telemetry
        val stat = StatFs(Environment.getDataDirectory().path)
        val blockSize = stat.blockSizeLong
        val totalStorageBytes = stat.blockCountLong * blockSize
        val freeStorageBytes = stat.availableBlocksLong * blockSize

        val totalJunk = items.sumOf { it.sizeBytes }

        CleanerScanResult(
            appCacheBytes = internalCacheSize,
            externalCacheBytes = externalCacheSize,
            tempFilesBytes = codeCacheSize,
            totalJunkBytes = totalJunk,
            totalStorageBytes = totalStorageBytes,
            freeStorageBytes = freeStorageBytes,
            items = items
        )
    }

    suspend fun cleanAppJunk(): Long = withContext(Dispatchers.IO) {
        var cleaned = 0L

        cleaned += deleteFolderContents(context.cacheDir)
        context.externalCacheDir?.let {
            cleaned += deleteFolderContents(it)
        }
        cleaned += deleteFolderContents(context.codeCacheDir)

        cleaned
    }

    private fun getFolderSize(file: File?): Long {
        if (file == null || !file.exists()) return 0L
        if (file.isFile) return file.length()

        var total = 0L
        file.listFiles()?.forEach { child ->
            total += getFolderSize(child)
        }
        return total
    }

    private fun deleteFolderContents(file: File?): Long {
        if (file == null || !file.exists()) return 0L
        var deleted = 0L

        file.listFiles()?.forEach { child ->
            if (child.isDirectory) {
                deleted += deleteFolderContents(child)
                child.delete()
            } else {
                val len = child.length()
                if (child.delete()) {
                    deleted += len
                }
            }
        }
        return deleted
    }
}
